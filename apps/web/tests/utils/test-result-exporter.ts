/**
 * Test Result Exporter
 * Exports test results to Markdown and CSV formats
 */

import { TestResult } from './types/test-types';
import Papa from 'papaparse';

/**
 * Export single test result to Markdown format
 */
export function exportToMarkdown(result: TestResult): string {
  const timestamp = new Date(result.timestamp).toLocaleString();

  let markdown = `# Test Result - ${timestamp}\n\n`;

  // Test Metadata
  markdown += `## Test Information\n\n`;
  markdown += `- **Test ID**: ${result.id}\n`;
  markdown += `- **Timestamp**: ${timestamp}\n`;
  markdown += `- **Model**: ${result.model.name} (${result.model.provider})\n`;
  markdown += `- **Occasion**: ${result.scenario.occasion}\n`;
  markdown += `- **Expected Category**: ${result.scenario.expectedCategory}\n`;
  markdown += `\n`;

  // Query
  markdown += `## User Query\n\n`;
  markdown += `\`\`\`\n${result.query}\n\`\`\`\n\n`;

  // LLM Response
  markdown += `## LLM Response\n\n`;
  markdown += `\`\`\`\n${result.response}\n\`\`\`\n\n`;

  // Evaluation Scores
  markdown += `## Evaluation Scores\n\n`;
  markdown += `| Criterion | Score/Result |\n`;
  markdown += `|-----------|-------------|\n`;
  markdown += `| Overall Quality | **${result.evaluationScore.overallQuality.toFixed(1)}/10** |\n`;
  markdown += `| Thai Language Tone | ${result.evaluationScore.thaiLanguageTone}/10 |\n`;
  markdown += `| Category Identification | ${result.evaluationScore.categoryIdentification ? '✓ PASS' : '✗ FAIL'} |\n`;
  markdown += `| Product Recommendation Count | ${result.evaluationScore.productRecommendationCount ? '✓ PASS' : '✗ FAIL'} |\n`;
  markdown += `| Central Online Links | ${result.evaluationScore.centralOnlineLinks}/10 |\n`;
  markdown += `| Styling Tips Count | ${result.evaluationScore.stylingTipsCount ? '✓ PASS' : '✗ FAIL'} |\n`;
  markdown += `| Response Structure | ${result.evaluationScore.responseStructure}/10 |\n`;
  markdown += `\n`;

  // Performance Metrics
  markdown += `## Performance Metrics\n\n`;
  markdown += `- **Tokens Used**: ${result.tokenUsage.totalTokens} (Prompt: ${result.tokenUsage.promptTokens}, Completion: ${result.tokenUsage.completionTokens})\n`;
  markdown += `- **Cost**: $${result.cost.toFixed(6)}\n`;
  markdown += `- **Response Time**: ${result.responseTime}ms\n`;
  markdown += `\n`;

  // Manual Review
  if (result.manualRating || result.manualNotes) {
    markdown += `## Manual Review\n\n`;
    if (result.manualRating) {
      markdown += `- **Rating**: ${result.manualRating === 'approved' ? '✓ Approved' : '⚠ Needs Improvement'}\n`;
    }
    if (result.manualNotes) {
      markdown += `- **Notes**: ${result.manualNotes}\n`;
    }
    markdown += `\n`;
  }

  // Reference Output
  if (result.scenario.referenceOutput) {
    markdown += `## Reference Output\n\n`;
    markdown += `\`\`\`\n${result.scenario.referenceOutput.substring(0, 500)}...\n\`\`\`\n\n`;
    markdown += `_Note: Reference output truncated for brevity_\n\n`;
  }

  markdown += `---\n\n`;
  markdown += `*Generated by OOTDay LLM Model Testing System*\n`;

  return markdown;
}

/**
 * Export multiple test results to combined Markdown
 */
export function exportMultipleToMarkdown(results: TestResult[]): string {
  const timestamp = new Date().toLocaleString();

  let markdown = `# LLM Model Testing Results\n\n`;
  markdown += `**Generated**: ${timestamp}\n`;
  markdown += `**Total Tests**: ${results.length}\n\n`;

  // Summary Table
  markdown += `## Summary\n\n`;
  markdown += `| # | Model | Occasion | Overall Score | Cost | Status |\n`;
  markdown += `|---|-------|----------|---------------|------|--------|\n`;

  results.forEach((result, index) => {
    const status = result.manualRating === 'approved' ? '✓' : result.manualRating === 'needs_improvement' ? '⚠' : '-';
    markdown += `| ${index + 1} | ${result.model.name} | ${result.scenario.occasion} | ${result.evaluationScore.overallQuality.toFixed(1)}/10 | $${result.cost.toFixed(6)} | ${status} |\n`;
  });

  markdown += `\n`;

  // Total Cost
  const totalCost = results.reduce((sum, r) => sum + r.cost, 0);
  markdown += `**Total Cost**: $${totalCost.toFixed(6)}\n\n`;

  markdown += `---\n\n`;

  // Individual Results
  markdown += `## Detailed Results\n\n`;
  results.forEach((result, index) => {
    markdown += `### Test ${index + 1}: ${result.model.name} - ${result.scenario.occasion}\n\n`;
    markdown += exportToMarkdown(result);
    markdown += `\n`;
  });

  return markdown;
}

/**
 * Export test results to CSV format
 */
export function exportToCSV(results: TestResult[]): string {
  const csvData = results.map(result => ({
    timestamp: result.timestamp,
    test_id: result.id,
    model_name: result.model.name,
    model_provider: result.model.provider,
    model_id: result.model.id,
    occasion: result.scenario.occasion,
    query: result.query,
    expected_category: result.scenario.expectedCategory,
    overall_quality: result.evaluationScore.overallQuality,
    thai_tone_score: result.evaluationScore.thaiLanguageTone,
    category_identification: result.evaluationScore.categoryIdentification ? 'PASS' : 'FAIL',
    product_count_check: result.evaluationScore.productRecommendationCount ? 'PASS' : 'FAIL',
    links_score: result.evaluationScore.centralOnlineLinks,
    tips_count_check: result.evaluationScore.stylingTipsCount ? 'PASS' : 'FAIL',
    structure_score: result.evaluationScore.responseStructure,
    prompt_tokens: result.tokenUsage.promptTokens,
    completion_tokens: result.tokenUsage.completionTokens,
    total_tokens: result.tokenUsage.totalTokens,
    cost_usd: result.cost,
    response_time_ms: result.responseTime,
    manual_rating: result.manualRating || '',
    manual_notes: result.manualNotes || '',
    response: result.response.replace(/\n/g, ' ').substring(0, 500) // Truncate for CSV
  }));

  return Papa.unparse(csvData);
}

/**
 * Download file to browser
 */
export function downloadFile(content: string, filename: string, mimeType: string): void {
  if (typeof window === 'undefined') {
    return;
  }

  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

/**
 * Generate filename with timestamp
 */
export function generateFilename(prefix: string, extension: string): string {
  const now = new Date();
  const year = now.getFullYear();
  const month = String(now.getMonth() + 1).padStart(2, '0');
  const day = String(now.getDate()).padStart(2, '0');
  const hours = String(now.getHours()).padStart(2, '0');
  const minutes = String(now.getMinutes()).padStart(2, '0');
  const seconds = String(now.getSeconds()).padStart(2, '0');

  return `${prefix}-${year}-${month}-${day}-${hours}${minutes}${seconds}.${extension}`;
}

/**
 * Export single test result and download as Markdown
 */
export function exportSingleResultToMarkdown(result: TestResult): void {
  const markdown = exportToMarkdown(result);
  const filename = generateFilename('test-result', 'md');
  downloadFile(markdown, filename, 'text/markdown');
}

/**
 * Export multiple test results and download as Markdown
 */
export function exportAllResultsToMarkdown(results: TestResult[]): void {
  const markdown = exportMultipleToMarkdown(results);
  const filename = generateFilename('test-results', 'md');
  downloadFile(markdown, filename, 'text/markdown');
}

/**
 * Export test results and download as CSV
 */
export function exportResultsToCSV(results: TestResult[]): void {
  const csv = exportToCSV(results);
  const filename = generateFilename('test-results', 'csv');
  downloadFile(csv, filename, 'text/csv');
}

/**
 * Export both Markdown and CSV
 */
export function exportResultsBoth(results: TestResult[]): void {
  exportAllResultsToMarkdown(results);
  exportResultsToCSV(results);
}

/**
 * Save results to session storage
 */
export function saveResultsToSession(results: TestResult[]): void {
  if (typeof window === 'undefined') {
    return;
  }

  sessionStorage.setItem('test-results', JSON.stringify(results));
}

/**
 * Load results from session storage
 */
export function loadResultsFromSession(): TestResult[] {
  if (typeof window === 'undefined') {
    return [];
  }

  const saved = sessionStorage.getItem('test-results');
  return saved ? JSON.parse(saved) : [];
}

/**
 * Clear results from session storage
 */
export function clearResultsFromSession(): void {
  if (typeof window === 'undefined') {
    return;
  }

  sessionStorage.removeItem('test-results');
}
